    await db.exec(`set test.uid='${admin}'`);
    const client = await one("insert into clientes(nombre_comercio,direccion) values ('Comercio','Privada') returning id");
    const p = await one("insert into productos(nombre,categoria,precio_normal,precio_promo,precio_interior,costo) values ('Papas Facu','Snacks',100,80,90,50) returning id");
    const food = await one("insert into productos(nombre,categoria,precio_normal,precio_promo,precio_interior) values ('Balanceado','Balanceados',300,200,250) returning id");
