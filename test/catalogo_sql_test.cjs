    const token = await configure('interior', {balanceados:'promo'}, {[p.id]:'normal'});
    assert.match(token,/^[a-f0-9]{64}$/);
    assert.notEqual((await one('select token_hash from catalogos_clientes')).token_hash, token);
    await db.exec('set role anon');
    const catalog = async token => (await one('select obtener_catalogo_cliente($1) c',[token])).c;
    const c = await catalog(token);
    assert.equal(c.nombre_comercio, 'Comercio'); assert.equal(c.productos.length,2);
    assert.equal(c.productos.find(x=>x.id===p.id).precio,100);
    assert.equal(c.productos.find(x=>x.id===food.id).precio,200);
    for (const x of c.productos) { assert.equal(x.costo,undefined); assert.equal(x.tipo,undefined); assert.equal(x.precio_interior,undefined); }
    await assert.rejects(db.query('select * from catalogos_clientes'),/permission denied/);
    await assert.rejects(db.query('select * from catalogo_productos_internos($1)',[client.id]),/permission denied/);
    await assert.rejects(catalog('f'.repeat(64)),/inválido/);
    const key = () => require('node:crypto').randomUUID();
    const submit = async (items,id=key()) => (await one('select crear_pedido_catalogo($1,$2,$3,$4) p',[token,id,JSON.stringify(items),'Entregar por la tarde'])).p;
    const cart = [{producto_id:p.id,cantidad:2,precio_visto:100},{producto_id:food.id,cantidad:1,precio_visto:200}];
    const request = key(); const order = await submit(cart,request);
    assert.equal(order.total,400); assert.deepEqual(await submit(cart,request),order);
    await assert.rejects(submit([{...cart[0],precio_visto:1}]),/precios cambiaron/);
    await assert.rejects(submit([{...cart[0],cantidad:-1}]),/Cantidad/);
    await assert.rejects(submit([{...cart[0],cantidad:1.5}]),/Cantidad/);
    await assert.rejects(submit([{...cart[0],cantidad:'NaN'}]),/Cantidad/);
    await assert.rejects(submit([cart[0],cart[0]]),/duplicado/);
    await assert.rejects(submit([{...cart[0],producto_id:key()}]),/disponible/);
    await assert.rejects(submit([]),/vacío/);
    await assert.rejects(submit([cart[0],{...cart[1],precio_visto:0}]),/precios cambiaron/);
    await db.exec('reset role');
    assert.equal(Number((await one('select count(*) n from pedidos')).n),1);
    assert.equal(Number((await one('select count(*) n from pedido_detalles')).n),2);
    const detail = await one('select * from pedido_detalles where producto_id=$1',[p.id]);
    assert.equal(Number(detail.costo_unitario),50); assert.equal(Number(detail.importe_comision),0); assert.equal(detail.tipo_precio,'normal');
    const stored = await one('select * from pedidos'); assert.equal(stored.preventista_id,admin); assert.equal(stored.estado,'pendiente'); assert.equal(stored.facturado,false);
    assert.match(stored.observacion,/Catálogo web/);
    assert.equal(stored.origen,'catalogo');
    await db.query('update pedido_detalles set porcentaje_comision=15,importe_comision=30 where pedido_id=$1',[order.pedido_id]);
    assert.equal(Number((await one('select sum(importe_comision) s from pedido_detalles')).s),0);
    assert.equal(await configure('normal', {balanceados:'promo'}, {}, false),null);
    await db.exec('set role anon'); assert.equal((await catalog(token)).productos.find(x=>x.id===p.id).precio,100); await db.exec('reset role');
    await db.query('update productos set precio_normal=101 where id=$1',[p.id]);
    await db.exec('set role anon'); await assert.rejects(submit(cart),/precios cambiaron/); await db.exec('reset role');
    const expiry = (await one('select vence_at from catalogos_clientes')).vence_at;
    assert.ok(new Date(expiry).getTime() > Date.now()+11.9*3600000);
    assert.ok(new Date(expiry).getTime() <= Date.now()+12*3600000);
    assert.equal(new Date((await catalog(token)).vence_at).getTime(),new Date(expiry).getTime());
    await configure('normal',{}, {}, false,true);
    assert.equal(new Date((await one('select vence_at from catalogos_clientes')).vence_at).getTime(),new Date(expiry).getTime());
    await db.exec("update catalogos_clientes set vence_at=clock_timestamp()-interval '1 second'");
    await db.exec('set role anon');
    await assert.rejects(catalog(token),/enlace venció/);
    await assert.rejects(submit(cart),/enlace venció/);
    await db.exec('reset role');
    assert.equal(Number((await one('select count(*) n from pedidos')).n),1);
    await configure('normal',{}, {}, false,false);
    await configure('normal',{}, {}, false,true);
    await assert.rejects(catalog(token),/enlace venció/);
    await configure('normal',{}, {}, false,false);
    await assert.rejects(catalog(token),/desactivado/); await assert.rejects(submit(cart,request),/desactivado/);
    const renewed=await configure('normal',{}, {}, true,true);
    await assert.rejects(catalog(token),/desactivado/); assert.ok((await catalog(renewed)).productos.length);
    await db.exec(`set role authenticated; set test.uid='${seller}'`);
    assert.ok((await db.query('select id from clientes')).rows.length>0);
    assert.ok((await db.query('select id from productos')).rows.length>0);
    await db.exec("set test.uid='00000000-0000-0000-0000-000000000099'");
    assert.equal((await db.query('select id from clientes')).rows.length,0);
    assert.equal((await db.query('select id from productos')).rows.length,0);
    assert.equal((await db.query('select id from usuarios')).rows.length,0);
    await assert.rejects(db.query("insert into clientes(nombre_comercio,direccion) values ('No autorizado','No autorizado')"),/row-level security/);
    await db.exec('reset role');
    await db.query('update usuarios set activo=false where id=$1',[seller]);
