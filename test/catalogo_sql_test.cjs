    await db.exec('reset role');
    await db.query('update usuarios set activo=true where id=$1',[seller]);
    await db.exec(`set test.uid='${seller}'; set role authenticated`);
    await assert.rejects(configure('normal'),/administrador/);
    assert.equal((await db.query('select * from catalogos_clientes')).rows.length,0);
